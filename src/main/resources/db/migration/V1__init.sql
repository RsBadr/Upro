-- Etat Leitner de chaque question deja vue
create table review_card (
    question_id    varchar(100) primary key,
    box            int          not null,
    next_review_on date         not null,
    attempts       int          not null,
    successes      int          not null
);

-- Niveau estime (Elo) par module
create table skill_rating (
    module_id varchar(100) primary key,
    rating    double precision not null,
    answers   int              not null
);

-- Journal de toutes les reponses : source de verite pour les bilans quotidiens
create table answer_log (
    id            bigint generated by default as identity primary key,
    question_id   varchar(100)     not null,
    module_id     varchar(100)     not null,
    question_level varchar(20)     not null,
    correct       boolean          not null,
    answered_at   timestamp        not null,
    answered_on   date             not null,
    rating_before double precision not null,
    rating_after  double precision not null
);
create index answer_log_day_idx on answer_log (answered_on, module_id);

-- Quiz du jour : liste ordonnee de questions
create table daily_quiz_item (
    quiz_date   date         not null,
    position    int          not null,
    question_id varchar(100) not null,
    primary key (quiz_date, position)
);

-- Bilan quotidien par module (historique de progression)
create table daily_snapshot (
    snapshot_date date             not null,
    module_id     varchar(100)     not null,
    rating        double precision not null,
    level         varchar(20)      not null,
    answers       int              not null,
    correct       int              not null,
    primary key (snapshot_date, module_id)
);
